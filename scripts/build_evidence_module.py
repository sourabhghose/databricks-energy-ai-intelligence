"""Generate evidence/captured_runs.py from the executed notebooks in notebooks/executed/.

The executed notebooks are Databricks job runs exported (with their printed outputs) by
scripts/export_run_evidence.py. This script copies the key output cells verbatim into a Python module, so the
execution evidence sits next to the code that produced it and is checked by tests/test_execution_evidence.py.

Usage:  python scripts/build_evidence_module.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXECUTED = ROOT / "notebooks" / "executed"
TARGET = ROOT / "evidence" / "captured_runs.py"

# name -> (executed notebook, source file in this repo that the job ran)
RUNS = {
    "INGEST_LIVE": ("ingest_live_nemweb_ingest.ipynb", "pipelines/01_nemweb_price_ingest.py"),
    "INGEST_LIVE_DQ": ("ingest_live_bronze_to_gold_dq.ipynb", "pipelines/13_nemweb_bronze_to_gold.py"),
    "BACKFILL": ("archive_backfill_archive_backfill.ipynb", "pipelines/36_nemweb_archive_backfill.py"),
    "DQ_QUARANTINE": ("dq_quarantine_sa1_bronze_to_gold_dq.ipynb", "pipelines/13_nemweb_bronze_to_gold.py"),
    "MODEL_TRAINING": ("model_training_train.ipynb", "models/nem_forecast/train.py"),
    "LIVE_INFERENCE": ("live_inference_forecast_pipeline.ipynb", "pipelines/05_forecast_pipeline.py"),
    "UC_GOVERNANCE": ("uc_governance_governance.ipynb", "setup/30_governance.py"),
    "EVIDENCE_VERIFICATION": ("evidence_verification_evidence_verification.ipynb", "notebooks/evidence_verification.py"),
}
NOISE = ("UserWarning", "DeprecationWarning", "google.protobuf", "warnings.warn", "service.py will be removed")


def run_record(name: str, nb_file: str, source: str) -> dict:
    nb = json.loads((EXECUTED / nb_file).read_text())
    meta = nb["metadata"]["databricks"]
    header = "".join(nb["cells"][0]["source"])
    started = header.split("started ", 1)[1].split(",", 1)[0] if "started " in header else ""
    result = "SUCCESS" if "**SUCCESS**" in header else header.split("result **", 1)[-1].split("**", 1)[0]
    outputs = []
    for cell in nb["cells"]:
        if cell["cell_type"] != "code" or not cell["outputs"]:
            continue
        text = "".join("".join(o["text"]) for o in cell["outputs"])
        lines = [ln.rstrip() for ln in text.splitlines() if not any(n in ln for n in NOISE)]
        if lines:
            outputs.append("\n".join(lines).strip())
    return {"job_run_id": meta["job_run_id"], "task_run_id": meta["task_run_id"], "started": started,
            "result": result, "source_file": source, "executed_notebook": f"notebooks/executed/{nb_file}",
            "cell_outputs": outputs}


def literal(text: str) -> str:
    """A readable triple-quoted literal for verbatim output (falls back to repr if the text contains quotes)."""
    if "'''" in text or text.endswith("\\"):
        return repr(text)
    return "r'''" + text + "'''"


def render(records: dict[str, dict]) -> str:
    out = ['"""Verbatim outputs of real Databricks job runs — the execution evidence for this build.',
           "",
           "GENERATED by scripts/build_evidence_module.py from the executed notebooks in notebooks/executed/ (Databricks",
           "job runs exported with their printed cell outputs). Do not edit by hand. Each record names the job run, the",
           "source file in this repo that the job executed, and the output cells exactly as printed.",
           "Workspace: fevm-serverless-stable-2b9lj3.cloud.databricks.com · catalog serverless_stable_2b9lj3_catalog.",
           "Checked by tests/test_execution_evidence.py.",
           '"""', "", "WORKSPACE = \"fevm-serverless-stable-2b9lj3.cloud.databricks.com\"",
           "CATALOG = \"serverless_stable_2b9lj3_catalog\"", ""]
    for name, rec in records.items():
        out.append(f"{name} = {{")
        for key in ("job_run_id", "task_run_id", "started", "result", "source_file", "executed_notebook"):
            out.append(f"    {key!r}: {rec[key]!r},")
        out.append("    'cell_outputs': [")
        for text in rec["cell_outputs"]:
            out.append(f"        {literal(text)},")
        out.append("    ],")
        out.append("}")
        out.append("")
    out.append("ALL_RUNS = {" + ", ".join(f"{n!r}: {n}" for n in records) + "}")
    out.append("")
    return "\n".join(out)


def main() -> None:
    records = {name: run_record(name, nb, src) for name, (nb, src) in RUNS.items()}
    TARGET.parent.mkdir(exist_ok=True)
    (TARGET.parent / "__init__.py").write_text('"""Execution evidence captured from real Databricks job runs."""\n')
    TARGET.write_text(render(records))
    print(f"wrote {TARGET.relative_to(ROOT)} ({TARGET.stat().st_size:,} bytes, {len(records)} runs)")


if __name__ == "__main__":
    main()
